"""Pydantic models: the evaluation contract (copied from the moulinette's
``models_public.py``) plus the configuration models used by this project.

The contract models (StepMetrics, SolutionOutput, MBPPTaskInput,
SWEBenchTaskInput) must stay field-compatible with the moulinette.
"""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import List, Optional

from pydantic import BaseModel, Field


# =============================================================================
# Evaluation contract (must match moulinette/models_public.py)
# =============================================================================

class StepMetrics(BaseModel):
    """Metrics for a single agent step (one LLM generate -> sandbox execute cycle)."""
    step: int = Field(..., description="1-indexed iteration number")
    input_tokens: int = Field(..., description="Tokens sent to the LLM for this step")
    output_tokens: int = Field(..., description="Tokens generated by the LLM for this step")
    request_time_ms: float = Field(..., description="Wall-clock time for the LLM API call in milliseconds")
    timestamp: str = Field(default_factory=lambda: datetime.now().isoformat())
    api_url: str = Field(default="")
    model_name: str = Field(default="")
    llm_output: str = Field(default="")
    sandbox_input: str = Field(default="")
    sandbox_output: str = Field(default="")
    retries: int = Field(default=0)


class SolutionOutput(BaseModel):
    """Output written to solution.json."""
    task_id: str
    benchmark: str
    success: bool
    solution: str
    iterations: int
    total_requests: int
    total_input_tokens: int
    total_output_tokens: int
    total_time_seconds: float
    steps: List[StepMetrics] = Field(default_factory=list)
    system_prompt: str = Field(default="")
    error: Optional[str] = Field(default=None)
    timestamp: str = Field(default_factory=lambda: datetime.now().isoformat())


class MBPPTaskInput(BaseModel):
    """Input for an MBPP task, provided by the moulinette."""
    task_id: int
    task_definition: str
    function_definition: str
    test_imports: List[str] = Field(default_factory=list)
    test_list: List[str] = Field(default_factory=list)


class SWEBenchTaskInput(BaseModel):
    """Input for a SWE-bench task, provided by the moulinette."""
    instance_id: str
    problem_statement: str
    docker_image: str
    eval_script: str
    hints_text: str = Field(default="")
    repo: str = Field(default="")


# =============================================================================
# Sandbox configuration
# =============================================================================

DEFAULT_AUTHORIZED_IMPORTS = [
    "math", "math.*",
    "collections", "collections.*",
    "itertools", "re", "json",
    "typing", "typing.*",
    "functools", "operator",
    "heapq", "bisect", "copy",
    "string", "random",
    "datetime", "datetime.*",
    "array", "cmath",
]


class SandboxConfig(BaseModel):
    """Sandbox configuration.

    Uses an allowlist approach: only imports in ``authorized_imports`` are
    allowed, only paths below ``allowed_directories`` can be opened.
    Everything else is blocked by default.
    """
    authorized_imports: List[str] = Field(default_factory=lambda: list(DEFAULT_AUTHORIZED_IMPORTS))
    allowed_directories: List[str] = Field(default_factory=lambda: ["/testbed", "/tmp/agent"])
    max_execution_time_seconds: int = 30
    max_memory_mb: int = 512
    # --- project extensions (not part of the subject's minimal model) ---
    max_output_chars: int = Field(
        default=6000,
        description="Observation size cap; longer output is truncated with an explicit notice.",
    )

    @classmethod
    def from_json_file(cls, path: str | Path) -> "SandboxConfig":
        """Load a configuration file; unknown keys are rejected by pydantic."""
        with open(path, encoding="utf-8") as f:
            return cls.model_validate(json.load(f))


# =============================================================================
# Hard limits enforced by the agent (VI.1 of the subject)
# =============================================================================

class RunLimits(BaseModel):
    """Budget for a single task. Token limits are cumulative over all requests."""
    max_iterations: int
    max_input_tokens: int
    max_output_tokens: int
    max_time_seconds: float

    @classmethod
    def mbpp(cls) -> "RunLimits":
        return cls(max_iterations=10, max_input_tokens=6_000,
                   max_output_tokens=1_500, max_time_seconds=120.0)

    @classmethod
    def swebench(cls) -> "RunLimits":
        return cls(max_iterations=30, max_input_tokens=300_000,
                   max_output_tokens=10_000, max_time_seconds=900.0)
